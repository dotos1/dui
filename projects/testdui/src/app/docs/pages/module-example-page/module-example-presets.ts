/**
 * Resolves a tailored `ModuleScenarioPreset` for any `category` and `moduleId`.
 * @zh 根据分类 `category` 与模块 `moduleId` 获取专属可交互演示场景预设；若未命中具体项则按分类返回智能默认预设。
 * @param category - Category identifier (`string`) / 分类标识（`string`）
 * @param moduleId - Module identifier (`string`) / 模块标识（`string`）
 * @param importPath - Full package import path (`string`) / 完整包导入路径（`string`）
 * @returns Resolved `ModuleScenarioPreset` / 解析后的场景预设配置（`ModuleScenarioPreset`）
 */
export function resolveModuleScenarioPreset(
  category: string,
  moduleId: string,
  importPath: string
): ModuleScenarioPreset {
  const key = `${category}/${moduleId}`;
  const exact = MODULE_SCENARIO_PRESETS[key];
  if (exact) {
    return exact;
  }

  const modeByCategory: Record<string, PlaygroundMode> = {
    base: 'core-service',
    common: 'overlay',
    container: 'dnd-layout',
    core: 'core-service',
    data: 'ux-widget',
    form: 'form-control',
    net: 'core-service',
    theme: 'color',
    translator: 'input-utility',
    tree: 'ux-widget',
    ui: 'toolbar',
    util: 'pipe-codec',
    ux: 'ux-widget',
  };

  return {
    mode: modeByCategory[category] || 'core-service',
    title: `${importPath} 可交互示例工作台`,
    subtitle: '实时调整下方组件输入参数、触发输出事件或方法调用，并同步生成可复制的 TypeScript / HTML 代码片段。',
    primaryLabel: '示例输入文本',
    primaryDefault: `${importPath} 实时交互演示`,
    numericLabel: '参数数值控制',
    numericDefault: 24,
    numericMin: 0,
    numericMax: 100,
    optionLabel: '预设配置模式',
    options: ['default', 'primary', 'accent', 'compact'],
    toggleLabel: '启用增强交互模式',
    actions: [
      { id: 'invoke', label: '触发示例交互动作', payload: `${importPath}: interactive action invoked` },
      { id: 'reset', label: '重置参数状态', payload: `${importPath}: state reset to defaults` },
    ],
  };
}
