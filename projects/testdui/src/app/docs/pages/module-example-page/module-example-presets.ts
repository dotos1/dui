/**
 * Interface `ScenarioActionPreset` defining a quick-action button in the interactive workbench.
 * @zh 接口 `ScenarioActionPreset`，定义可交互示例工作台中的快捷操作按钮配置。
 */
export interface ScenarioActionPreset {
  /**
   * Property `id` (`string`) storing action identifier.
   * @zh 属性 `id`（类型：`string`），用于存储快捷动作唯一标识。
   */
  id: string;
  /**
   * Property `label` (`string`) storing button display label.
   * @zh 属性 `label`（类型：`string`），用于存储按钮显示文案。
   */
  label: string;
  /**
   * Property `payload` (`string`) storing action payload description.
   * @zh 属性 `payload`（类型：`string`），用于存储触发动作时的负载描述。
   */
  payload: string;
}

/**
 * Interface `ModuleScenarioPreset` defining the tailored interactive playground configuration for a module.
 * @zh 接口 `ModuleScenarioPreset`，定义单个模块专属的可交互演示场景配置。
 */
export interface ModuleScenarioPreset {
  /**
   * Property `mode` (`PlaygroundMode`) storing visual workbench mode.
   * @zh 属性 `mode`（类型：`PlaygroundMode`），用于存储视觉工作台模式。
   */
  mode: PlaygroundMode;
  /**
   * Property `title` (`string`) storing interactive demo title.
   * @zh 属性 `title`（类型：`string`），用于存储可交互演示标题。
   */
  title: string;
  /**
   * Property `subtitle` (`string`) storing interactive demo description.
   * @zh 属性 `subtitle`（类型：`string`），用于存储可交互演示说明文案。
   */
  subtitle: string;
  /**
   * Property `primaryLabel` (`string`) storing primary control label.
   * @zh 属性 `primaryLabel`（类型：`string`），用于存储主交互文本控件标签。
   */
  primaryLabel: string;
  /**
   * Property `primaryDefault` (`string`) storing default text value.
   * @zh 属性 `primaryDefault`（类型：`string`），用于存储主交互文本默认值。
   */
  primaryDefault: string;
  /**
   * Property `numericLabel` (`string`) storing numeric slider label.
   * @zh 属性 `numericLabel`（类型：`string`），用于存储数值滑块控件标签。
   */
  numericLabel: string;
  /**
   * Property `numericDefault` (`number`) storing default numeric value.
   * @zh 属性 `numericDefault`（类型：`number`），用于存储数值滑块默认值。
   */
  numericDefault: number;
  /**
   * Property `numericMin` (`number`) storing minimum slider value.
   * @zh 属性 `numericMin`（类型：`number`），用于存储数值滑块最小值。
   */
  numericMin: number;
  /**
   * Property `numericMax` (`number`) storing maximum slider value.
   * @zh 属性 `numericMax`（类型：`number`），用于存储数值滑块最大值。
   */
  numericMax: number;
  /**
   * Property `optionLabel` (`string`) storing option selector label.
   * @zh 属性 `optionLabel`（类型：`string`），用于存储模式下拉或枚举切换标签。
   */
  optionLabel: string;
  /**
   * Property `options` (`string[]`) storing selectable options.
   * @zh 属性 `options`（类型：`string[]`），用于存储可切换的枚举选项列表。
   */
  options: string[];
  /**
   * Property `toggleLabel` (`string`) storing boolean switch label.
   * @zh 属性 `toggleLabel`（类型：`string`），用于存储布尔开关标签。
   */
  toggleLabel: string;
  /**
   * Property `actions` (`ScenarioActionPreset[]`) storing preset interactive actions.
   * @zh 属性 `actions`（类型：`ScenarioActionPreset[]`），用于存储可点击的预设交互动作列表。
   */
  actions: ScenarioActionPreset[];
}

